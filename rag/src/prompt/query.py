# User prompt template for answering questions based on document content
QUERY_USER_PROMPT_TEMPLATE = """
基于以下文档内容回答问题。

【下游处理说明（非常重要）】
你的回答会被自动流程做结构化解析与一致性核验，重点关注：
- 是否覆盖问题要求的全部关键要点
- 是否遗漏重要维度或结构性信息
- 年份、日期、金额、比例等数值是否与证据一致

---

【输入信息】
你将收到：
1. 问题（question）
2. 多个证据片段（contexts），每个片段包含：
   - filename
   - page
   - content

---

【强制回答规则（请严格遵守）】

1. 【覆盖优先原则】
   - 如果问题是“有哪些 / 如何 / 原因 / 驱动因素 / 模式 / 结构 / 对比差异”等列举型问题：
     - 必须使用“分点列举”的形式回答；
     - 禁止只给空泛的一句总结；至少输出 1 条编号要点。
     - 只列出与问题直接相关、且能从证据中明确对应到的要点；不要为了凑条目而扩写行业通用原因。
     - 若问题未明确要求“全面列举”（例如未出现“有哪些/分别/从哪些方面/具体”），默认回答 1-2 个最关键因素即可。
     - 若证据只明确支持 1 个关键要点，允许只回答 1 点；该 1 点允许只写 1 句话，尽量复用证据原句，不要额外扩写。

2. 【结构展开原则】
   - 若证据中涉及多个维度（例如：产品分类 + 收入结构，或 渠道 + 定价方式）：
     - 必须在答案中分别列出；
     - 不得合并为模糊的一句话概括。

3. 【数值与事实准确性（最高优先级）】
   - 涉及年份、日期、金额、百分比、数量、占比等信息时：
     - 必须与证据片段中的原文保持一致；
     - 不得混用不同年份、不同报告或不同口径的数据。
   - 若证据无法唯一确定具体数值：
     - 明确写出“无法从提供的文档中确定”，
     - 并说明缺失的是哪一年、哪一页或哪张表。

4. 【多因素问题的处理】
   - 若问题本身是“多因素 / 多原因 / 多驱动”类问题：
     - 只回答证据中明确出现的因素；
     - 若证据只明确给出 1 个关键因素，则只写 1 点即可，不要为了凑数量扩写；
     - 若证据明确包含多个因素，再按 2+ 点列举。

5. 【禁止过度压缩】
   - 不要为了简洁而删除文档中已明确出现的重要信息；
   - 避免“多答但引入无关数字/细节”，优先保证与问题直接相关且可被证据支撑。

---

【回答格式强烈建议】
- 使用编号列表（1. 2. 3. …）
- 每一点对应一个明确事实或结论
- 避免仅使用“主要是”“总体来看”等模糊表述

---

【文档内容】
{context_text}

【问题】
{question}
"""